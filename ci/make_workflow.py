"""Generate .github/workflows/sweep.yml (run: python ci/make_workflow.py)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PAIRS = json.load(open(os.path.join(HERE, "sweep_config.json")))["pairs_full"]

SETUP = """      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with:
          python-version: "3.13"
      - name: Install dependencies (CPU-only torch)
        run: |
          python -m pip install --upgrade pip -q
          pip install -q -r ci/requirements-ci.txt
          pip install -q torch==2.14.1 --index-url https://download.pytorch.org/whl/cpu || pip install -q torch --index-url https://download.pytorch.org/whl/cpu
"""

M1_RESTORE = """      - name: Restore M1 data of ${{ matrix.pair }}
        id: m1
        uses: actions/cache/restore@v4
        with:
          path: |
            data/m1/${{ matrix.pair }}
            data/manifests/acq_${{ matrix.pair }}.jsonl
          key: m1-v2-${{ matrix.pair }}-${{ needs.plan.outputs.first_year }}
"""

SWEEP_BODY = """    steps:
""" + SETUP + M1_RESTORE + """      - name: Download data if the cache was evicted
        if: steps.m1.outputs.cache-hit != 'true'
        run: python ci/data_job.py --pair ${{ matrix.pair }} --first-year ${{ needs.plan.outputs.first_year }} --last-year ${{ needs.plan.outputs.last_year }}
      - name: Restore cross-instrument panel
        uses: actions/cache/restore@v4
        with:
          path: data/panel
          key: panel-v1-${{ needs.plan.outputs.mode }}-${{ github.run_id }}
      - name: Run
        env:
          FXLAB_PANEL_DIR: data/panel
        run: |
          mkdir -p data/manifests
          cp data/manifests/acq_${{ matrix.pair }}.jsonl data/manifests/acquisition.jsonl || true
          python ci/sweep_job.py --pair ${{ matrix.pair }} %ARGS%
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: res-${{ matrix.pair }}-%TAG%
          path: out/res-${{ matrix.pair }}-%TAG%/
          retention-days: 14
          if-no-files-found: ignore
      - name: Report failure details as annotations
        if: failure()
        run: |
          for f in out/*.json out/*/job.log out/*/job.log.features; do
            [ -f "$f" ] || continue
            msg=$(tail -c 3500 "$f" | tr '%' ' ' | tr '\\n' '|')
            echo "::error title=$f::$msg"
          done
"""


def sweep_job(name, matrix_key, args, tag, workers):
    return f"""  {name}:
    needs: [plan, panel]
    if: needs.plan.outputs.{matrix_key} != ''
    runs-on: ubuntu-latest
    timeout-minutes: 350
    strategy:
      fail-fast: false
      max-parallel: 20
      matrix: ${{{{ fromJSON(needs.plan.outputs.{matrix_key}) }}}}
""" + SWEEP_BODY.replace("%ARGS%", args + f" --workers {workers}").replace("%TAG%", tag)


panel_restores = "".join(f"""      - uses: actions/cache/restore@v4
        if: contains(needs.plan.outputs.pairs_csv, ',{p},')
        with:
          path: data/closes/{p}_*.parquet
          key: closes-v1-{p}-${{{{ needs.plan.outputs.first_year }}}}-${{{{ github.run_id }}}}
""" for p in PAIRS)

wf = f"""# GENERATED by ci/make_workflow.py - edit that file, not this one.
name: full-sweep
on:
  workflow_dispatch:
  push:
    branches: [main]
    paths: ["ci/RUN", "ci/sweep_config.json"]
permissions:
  contents: write
  actions: write
concurrency:
  group: sweep
  cancel-in-progress: true
env:
  PYTHONUNBUFFERED: "1"
  POLARS_MAX_THREADS: "2"
  OMP_NUM_THREADS: "1"
  MKL_NUM_THREADS: "1"
  OPENBLAS_NUM_THREADS: "1"
jobs:
  plan:
    runs-on: ubuntu-latest
    outputs:
      mode: ${{{{ steps.p.outputs.mode }}}}
      first_year: ${{{{ steps.p.outputs.first_year }}}}
      last_year: ${{{{ steps.p.outputs.last_year }}}}
      pairs_csv: ${{{{ steps.p.outputs.pairs_csv }}}}
      data: ${{{{ steps.p.outputs.data }}}}
      hi: ${{{{ steps.p.outputs.hi }}}}
      lo: ${{{{ steps.p.outputs.lo }}}}
      models: ${{{{ steps.p.outputs.models }}}}
    steps:
      - uses: actions/checkout@v4
      - id: p
        run: python ci/plan.py

  data:
    needs: plan
    if: needs.plan.outputs.mode != 'off'
    runs-on: ubuntu-latest
    timeout-minutes: 350
    strategy:
      fail-fast: false
      max-parallel: 20
      matrix: ${{{{ fromJSON(needs.plan.outputs.data) }}}}
    steps:
{SETUP}{M1_RESTORE}      - name: Download, audit, closes
        run: |
          ARGS="--pair ${{{{ matrix.pair }}}} --first-year ${{{{ needs.plan.outputs.first_year }}}} --last-year ${{{{ needs.plan.outputs.last_year }}}}"
          if [ "${{{{ steps.m1.outputs.cache-hit }}}}" = "true" ]; then ARGS="$ARGS --skip-download"; fi
          python ci/data_job.py $ARGS
      - name: Save M1 data
        if: steps.m1.outputs.cache-hit != 'true'
        uses: actions/cache/save@v4
        with:
          path: |
            data/m1/${{{{ matrix.pair }}}}
            data/manifests/acq_${{{{ matrix.pair }}}}.jsonl
          key: m1-v2-${{{{ matrix.pair }}}}-${{{{ needs.plan.outputs.first_year }}}}
      - name: Save closes
        uses: actions/cache/save@v4
        with:
          path: data/closes/${{{{ matrix.pair }}}}_*.parquet
          key: closes-v1-${{{{ matrix.pair }}}}-${{{{ needs.plan.outputs.first_year }}}}-${{{{ github.run_id }}}}
      - uses: actions/upload-artifact@v4
        with:
          name: audit-${{{{ matrix.pair }}}}
          path: out/
          retention-days: 30
      - name: Report failure details as annotations
        if: failure()
        run: |
          for f in out/*.json out/*/job.log out/*/job.log.features; do
            [ -f "$f" ] || continue
            msg=$(tail -c 3500 "$f" | tr '%' ' ' | tr '\\n' '|')
            echo "::error title=$f::$msg"
          done

  panel:
    needs: [plan, data]
    if: always() && needs.plan.result == 'success' && needs.plan.outputs.mode != 'off'
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with:
          python-version: "3.13"
      - run: pip install -q pandas pyarrow
{panel_restores}      - run: python ci/panel_job.py
      - uses: actions/cache/save@v4
        with:
          path: data/panel
          key: panel-v1-${{{{ needs.plan.outputs.mode }}}}-${{{{ github.run_id }}}}
      - name: Free cache space (closes are merged into the panel now)
        env:
          GH_TOKEN: ${{{{ github.token }}}}
        run: |
          for k in $(gh cache list --repo ${{{{ github.repository }}}} --key closes-v1- --limit 100 --json key --jq '.[].key'); do
            gh cache delete "$k" --repo ${{{{ github.repository }}}} || true
          done

{sweep_job("sweep_hi", "hi", "--tf ${{ matrix.tf }} --part strategies --budget-min 320", "${{ matrix.tf }}", 3)}
{sweep_job("sweep_lo", "lo", "--tf ${{ matrix.tf }} --part strategies --budget-min 320", "${{ matrix.tf }}", 3)}
{sweep_job("models", "models", "--part models --budget-min 320", "models", 4)}
  collect:
    needs: [plan, sweep_hi, sweep_lo, models]
    if: always() && needs.plan.result == 'success' && needs.plan.outputs.mode != 'off'
    runs-on: ubuntu-latest
    timeout-minutes: 300
    steps:
{SETUP}      - uses: actions/download-artifact@v4
        with:
          pattern: res-*
          path: in/
      - uses: actions/download-artifact@v4
        with:
          pattern: audit-*
          path: audits/
          merge-multiple: true
      - run: python ci/collect.py
      - name: Publish summaries to the results branch
        run: |
          git config user.name "fxlab-sweep"
          git config user.email "fxlab-sweep@users.noreply.github.com"
          mkdir -p /tmp/pub && cp -r sweep_results /tmp/pub/
          git checkout --orphan results-tmp
          git rm -rq --cached . || true
          rm -rf ./* .github || true
          cp -r /tmp/pub/sweep_results .
          echo "run ${{{{ github.run_id }}}} mode ${{{{ needs.plan.outputs.mode }}}} $(date -u +%FT%TZ)" > sweep_results/RUN.txt
          git add sweep_results
          git commit -qm "Sweep results (run ${{{{ github.run_id }}}}, ${{{{ needs.plan.outputs.mode }}}})"
          git push -f origin HEAD:results
"""
os.makedirs(os.path.join(HERE, "..", ".github", "workflows"), exist_ok=True)
open(os.path.join(HERE, "..", ".github", "workflows", "sweep.yml"), "w").write(wf)
print("written", len(wf), "chars")
